#!/usr/bin/env bash

# ----------------------------------------------------------------------
#  Script:  mst_ip_setup.sh
#  Purpose: mst 서비스 시작 → ibdev2netdev 로부터 실제 인터페이스 획득
#           → IP 주소가 이미 있으면 건너뛰고, 없으면 할당 후 up
# ----------------------------------------------------------------------
set -euo pipefail          # 에러시 즉시 종료 (하지만 아래에서 예외 처리)

# -------------------------------------------------
# 1) mst 서비스 시작 + 상태 확인
# -------------------------------------------------
echo "=== 1) mst 서비스 시작 ==="
sudo mst start
sudo mst status

# -------------------------------------------------
# 2) ibdev2netdev 로부터 인터페이스 이름 얻기
# -------------------------------------------------
echo "=== 2) ibdev2netdev 로부터 dev_name 추출 ==="
DEV_NAME=$(ibdev2netdev | awk '/==>/ {print $5}')

if [[ -z "$DEV_NAME" ]]; then
    echo "ERROR: 디바이스 이름을 찾을 수 없습니다."
    exit 1
fi
echo "찾은 디바이스 이름: $DEV_NAME"

# -------------------------------------------------
# 3) IP 주소가 이미 존재하는지 검사하고, 없으면 추가
# -------------------------------------------------
IP_ADDR="10.0.0.1/24"

echo "=== 3) $DEV_NAME 에 IP $IP_ADDR 할당 (있으면 건너뛰기) ==="

# ① 현재 인터페이스에 동일한 주소가 있는지 확인
if ip addr show dev "$DEV_NAME" | grep -qw "${IP_ADDR%/*}"; then
    echo "  -> $IP_ADDR 가 이미 존재합니다. 추가를 건너뜁니다."
else
    # 실제 할당 시도 (실패해도 스크립트가 멈추지 않게 함)
    if sudo ip addr add "$IP_ADDR" dev "$DEV_NAME"; then
        echo "  -> 주소가 정상적으로 추가되었습니다."
    else
        # ip 명령이 실패했지만, 위의 존재 여부 검사에서 놓친 경우(예: 동일 주소가 다른 prefix 로 존재)
        echo "  -> 주소 추가 중 오류가 발생했지만 무시하고 진행합니다."
    fi
fi

# -------------------------------------------------
# 4) 인터페이스 up
# -------------------------------------------------
echo "=== 4) $DEV_NAME 인터페이스 up ==="
sudo ip link set "$DEV_NAME" up

echo "=== 모든 작업이 정상적으로 완료되었습니다. ==="
